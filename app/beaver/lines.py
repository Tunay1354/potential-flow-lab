class Picker:
    """memory: how many of a key's last lines are never picked again — half of its lines (at least 3, never all),
    so even a key said often does not repeat soon."""

    def __init__(self, seed=None, memory: int | None = None):
        self.rng = random.Random(seed)
        self.recent = {}
        self.memory = memory

    def pick(self, key: str, **fmt) -> str:
        options = LINES[key]
        recent = self.recent.setdefault(key, [])
        choices = [o for o in options if o not in recent] or options
        line = self.rng.choice(choices)
        recent.append(line)
        keep = self.memory if self.memory is not None else max(3, len(options) // 2)
        del recent[:-min(keep, max(1, len(options) - 1))]
        return line.format(**fmt) if fmt else line
