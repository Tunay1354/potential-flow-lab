"""
images.py — method of images for symmetry walls.

`resolve(elements)` turns the user's element list into the list of flow elements that are actually
summed: the enabled flow elements plus their images in every wall (walls themselves add no velocity).

Images are generated by repeated reflection (breadth-first):
    level 0: the user's flow elements
    level L: every level L−1 element mirrored in every wall (duplicates removed)
The process stops when no new image appears ("closed"), or after `max_levels` levels ("truncated").

    * one wall                          -> closes after 1 level   (exact)
    * two walls meeting at π/k          -> closes, 2k − 1 images (exact), e.g. 90° corner: 3 images
    * other angles                      -> some image falls INSIDE the fluid region: the boundary
                                           condition cannot be met exactly (error)
    * 3 or more walls                   -> truncated series if it does not close (warning)

Sector (wedge) flow: its two sides are walls for the OTHER elements (implied_walls), so a source,
vortex or doublet inside a wedge with β = 180°/k gets exact corner images; the sector flow itself is
not imaged (it already satisfies its walls). Other β, several sectors, or a sector together with
symmetry walls are reported as errors.

Two parallel walls (a channel of width H) need infinitely many images: every element e and its
mirror image e' in the first wall repeat with period P = 2H along the wall normal. These infinite
rows are summed in closed form, e.g.  Σ_n 1/(z − a − nP) = (π/P) cot(π(z − a)/P),  so the
channel is also exact (see PeriodicRow and the elements' periodic_* methods).
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from .base import FlowElement, Issue, normalize_angle

DEFAULT_MAX_LEVELS = 16


class ResolvedFlows(list):
    """Flow elements to sum (user's enabled flow elements + wall images).
    Passing this object to field functions avoids resolving the images again."""

    def __init__(self, items, system: "ImageSystem | None" = None):
        super().__init__(items)
        self.system = system
        groups: dict[type, list] = {}
        for e in items:
            groups.setdefault(type(e), []).append(e)
        self.groups = groups


@dataclass(kw_only=True)
class PeriodicRow(FlowElement):
    """Internal element: `base` repeated every `period` (infinitely many copies, closed-form sum)."""
    TYPE = "periodic_row"
    NAME = "Periodic image row"

    base: FlowElement | None = None
    period: complex = 0j

    def complex_velocity(self, z):
        return self.base.periodic_complex_velocity(z, self.period)

    def complex_potential(self, z):
        return self.base.periodic_complex_potential(z, self.period)

    def singular_points(self):
        return self.base.singular_points()          # the copies are outside the fluid

    def kernel_terms(self):
        """Rows of poles in closed form:  Σ c/(z − z0 − nP) = c (π/P) cot(π(z − z0)/P),
        Σ −c/(z − z0 − nP)² = −c (π/P)² (1 + cot²(π(z − z0)/P))."""
        terms = self.base.kernel_terms()
        if terms is None:
            return None
        out = []
        for t in terms:
            if t[0] == "pole1":
                out.append(("row1", t[1], t[2], self.period))
            elif t[0] == "pole2":
                out.append(("row2", t[1], t[2], self.period))
            else:
                return None
        return out


@dataclass
class ImageSystem:
    flows: list = field(default_factory=list)       # originals + images
    walls: list = field(default_factory=list)
    n_images: int = 0
    closed: bool = True                             # False -> series truncated
    periodic: bool = False                          # True -> channel, infinite rows in closed form
    issues: list = field(default_factory=list)      # list[Issue]

    @property
    def exact(self) -> bool:
        return self.closed and not any(i.is_error for i in self.issues)


def _key(e: FlowElement):
    vals = []
    for p in e.PARAMS:
        v = getattr(e, p.key)
        if p.is_angle:
            v = normalize_angle(v)
        vals.append(round(float(v), 9) + 0.0)       # + 0.0 turns −0.0 into 0.0
    return (e.TYPE, tuple(vals))


def build_image_system(elements, max_levels: int = DEFAULT_MAX_LEVELS) -> ImageSystem:
    act = [e for e in elements if e.enabled]
    walls = [e for e in act if e.IS_BOUNDARY]
    originals = [e for e in act if not e.IS_BOUNDARY]
    system = ImageSystem(flows=list(originals), walls=walls)

    # elements with walls of their own (sector flow): their sides act as walls for the others
    domains = [e for e in originals if e.implied_walls() is not None]
    if domains:
        if len(domains) > 1:
            system.issues.append(Issue("error", "Only one sector (wedge) flow can be used at a time: "
                                                "each one defines its own fluid region."))
            return system
        if walls:
            system.issues.append(Issue("error", "A sector (wedge) flow already has its own walls; it cannot "
                                                "be combined with symmetry walls."))
            return system
        dom = domains[0]
        others = [e for e in originals if e is not dom]
        if not others:
            return system                                   # the sector flow alone satisfies its walls
        walls = dom.implied_walls()
        if not walls:                                       # β > 180°: not an intersection of half-planes
            system.issues.append(Issue(
                "error", f"Other elements cannot be added to a sector flow with β = {dom.beta_deg:.4g}° > 180°: "
                         f"its walls cannot be represented with images, so V·n = 0 would not hold."))
            return system
        system.walls = walls
    if not walls:
        return system

    # uniform flows are not imaged: they must be parallel to every wall
    for e in originals:
        fv = e.freestream_velocity()
        if fv is None or abs(fv) == 0:
            continue
        for w in walls:
            cross = (np.conj(w.direction) * fv).imag / abs(fv)       # sin(angle between them)
            if abs(cross) > 1e-9:
                system.issues.append(Issue(
                    "error", f"{e.NAME} (α = {math.degrees(math.atan2(fv.imag, fv.real)):.4g}°) is not "
                             f"parallel to the wall (θ_w = {w.theta_w:.4g}°): V·n = 0 cannot hold far away."))

    if len(walls) == 2 and abs((np.conj(walls[0].direction) * walls[1].direction).imag) < 1e-12:
        return _channel(system, originals, walls)

    seen = {_key(e) for e in originals}
    frontier = list(originals)
    images = []
    system.closed = False
    for _ in range(max_levels):
        new = []
        for e in frontier:
            for w in walls:
                try:
                    m = e.mirrored(w)
                except NotImplementedError as exc:
                    system.issues.append(Issue("error", str(exc)))
                    continue
                if m is None:
                    continue
                k = _key(m)
                if k in seen:
                    continue
                seen.add(k)
                new.append(m)
        if not new:
            system.closed = True
            break
        images.extend(new)
        frontier = new

    system.flows = list(originals) + images
    system.n_images = len(images)

    # an image inside the fluid region means the walls cannot be represented by images exactly
    # (only meaningful if the user's elements themselves are inside the fluid; otherwise
    #  validation.py already reports "behind the wall" / "on the wall")
    fluid = lambda z: all(bool(w.signed_distance(z) > 1e-9 * (1 + abs(z))) for w in walls)  # noqa: E731
    originals_ok = all(fluid(p) for e in originals for p in e.singular_points())
    inside = [m for m in images for p in m.singular_points() if fluid(p)]
    if inside and originals_ok:
        system.issues.append(Issue(
            "error", "With this wall arrangement an image falls inside the fluid, so V·n = 0 cannot be "
                     "satisfied exactly (two walls, or the sides of a sector flow, must meet at an angle "
                     "of 180°/k, e.g. 90°, 60°, 45°)."))
    elif not system.closed and originals_ok:
        system.issues.append(Issue(
            "warning", f"The image series does not close (e.g. parallel walls): truncated after "
                       f"{max_levels} reflections, so V·n on the walls is only approximately zero."))
    return system


def _channel(system: ImageSystem, originals, walls) -> ImageSystem:
    """Two parallel walls facing each other: exact closed-form periodic images."""
    a, b = walls
    width = float(a.signed_distance(b.point))
    facing = (a.normal * np.conj(b.normal)).real < 0 and width > 0
    if not facing:
        system.issues.append(Issue("error", "Two parallel walls must face each other (fluid between them)."))
        return system
    period = 2.0 * width * a.normal
    flows = []
    for e in originals:
        try:
            m = e.mirrored(a)
            if m is None:                       # freestream (checked parallel above): not imaged
                flows.append(e)
                continue
            e.periodic_complex_velocity(np.array([0j]), period)     # raises if not supported
        except NotImplementedError as exc:
            system.issues.append(Issue("error", str(exc)))
            continue
        flows.append(PeriodicRow(base=e, period=period))
        flows.append(PeriodicRow(base=m, period=period))
    system.flows = flows
    system.periodic = True
    system.closed = True
    system.n_images = -1                        # infinitely many (summed in closed form)
    return system


def resolve(elements) -> ResolvedFlows:
    """Enabled flow elements + wall images, ready to be summed."""
    if isinstance(elements, ResolvedFlows):
        return elements
    system = build_image_system(elements)
    return ResolvedFlows(system.flows, system)
